#!/usr/bin/env python3
"""Generate src/d3d_probe.cpp: a counting wrapper for every entry point of a
code region (functions called from outside it), reported per frame.

Usage: gen_d3d_probe.py LO HI

At runtime the probe is off unless FH2_D3D_PROBE=1. Every 300 VdSwap calls it
logs the per-frame call count of each entry point that was called, sorted.
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
lo, hi = int(sys.argv[1], 16), int(sys.argv[2], 16)
data = json.load(open(os.path.join(ROOT, "tools", "callgraph.json")))
addr = lambda n: int(n[4:], 16) if n.startswith("sub_") else None
inside = lambda n: (a := addr(n)) is not None and lo <= a < hi
entries = set()
for caller, callees in data.items():
    for callee in callees:
        if inside(callee) and not inside(caller):
            entries.add(callee)
entries = sorted(entries - {"sub_82B72A90"})  # already wrapped in the hooks file

out = [
    "// Generated by tools/gen_d3d_probe.py -- per-frame call counts for the",
    f"// {len(entries)} entry points of {lo:08X}-{hi:08X}. FH2_D3D_PROBE=1 to enable.",
    "#include <atomic>",
    "#include <cstdlib>",
    "#include <cstdint>",
    "#include <algorithm>",
    "#include <vector>",
    "#include <chrono>",
    "#include <thread>",
    "#include <rex/logging.h>",
    "#include \"generated/default/forzahorizon2_init.h\"",
    "",
    "namespace {",
    "const bool g_probe_on = [] { const char* v = std::getenv(\"FH2_D3D_PROBE\"); return v && *v == '1'; }();",
    f"constexpr uint32_t kEntryCount = {len(entries)};",
    "constexpr uint32_t kEntryAddresses[kEntryCount] = {",
]
out += [f"    0x{name[4:]}," for name in entries]
out += [
    "};",
    "std::atomic<uint64_t> g_counts[kEntryCount];",
    "}  // namespace",
    "",
]
for i, name in enumerate(entries):
    out += [
        f"extern \"C\" void __imp__{name}(PPCContext& ctx, uint8_t* base);",
        f"extern \"C\" REX_FUNC({name}) {{",
        f"  if (g_probe_on) g_counts[{i}].fetch_add(1, std::memory_order_relaxed);",
        f"  __imp__{name}(ctx, base);",
        "}",
    ]
out += [
    "",
    "// Logs per-second call rates every 10 s from a background thread.",
    "namespace {",
    "struct ProbeReporter {",
    "  ProbeReporter() {",
    "    if (!g_probe_on) return;",
    "    std::thread([] {",
    "      while (true) {",
    "        std::this_thread::sleep_for(std::chrono::seconds(10));",
    "        std::vector<std::pair<uint64_t, uint32_t>> rows;",
    "        for (uint32_t i = 0; i < kEntryCount; ++i) {",
    "          uint64_t n = g_counts[i].exchange(0);",
    "          if (n) rows.emplace_back(n, kEntryAddresses[i]);",
    "        }",
    "        std::sort(rows.rbegin(), rows.rend());",
    "        for (auto& [n, a] : rows) {",
    "          REXLOG_WARN(\"[D3DPROBE] sub_{:08X} {:.1f}/s\", a, double(n) / 10.0);",
    "        }",
    "      }",
    "    }).detach();",
    "  }",
    "} g_probe_reporter;",
    "}  // namespace",
]
path = os.path.join(ROOT, "src", "forzahorizon2_d3d_probe.cpp")
open(path, "w").write("\n".join(out) + "\n")
print(f"{len(entries)} wrappers -> {path}")
